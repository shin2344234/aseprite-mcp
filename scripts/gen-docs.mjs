// Generates docs/tools.md from the tool schemas the server actually registers.
// Usage: npm run docs   (after npm run build)
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const client = new Client({ name: "gen-docs", version: "0" });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(root, "dist", "index.js")], stderr: "ignore" }));
const { tools } = await client.listTools();
const instructions = client.getInstructions?.() ?? "";
await client.close();

// Sections in the order the README describes them; anything unlisted lands in "Other".
const SECTIONS = [
  ["Setup and status", ["status", "install_extension", "launch_aseprite"]],
  ["Generic access", ["run_lua", "run_command", "list_commands", "api_docs", "cli"]],
  ["Application state", ["app_state", "set_active", "undo_redo", "list_preferences", "preferences", "view_settings"]],
  ["Sprites", ["list_sprites", "new_sprite", "open_sprite", "get_sprite_info", "save_sprite", "close_sprite", "duplicate_sprite", "set_sprite_properties", "resize_sprite", "canvas_size", "crop_sprite", "change_color_mode", "flip_rotate"]],
  ["Layers", ["add_layer", "update_layer", "delete_layer", "duplicate_layer", "merge_layers", "convert_layer"]],
  ["Frames", ["add_frames", "delete_frames", "set_frame_duration", "move_frame"]],
  ["Cels", ["get_cels", "update_cel", "delete_cel", "copy_cel", "link_cels"]],
  ["Drawing and pixels", ["draw_pixels", "get_pixels", "use_tool", "draw_shapes", "draw_text", "draw_image", "clear", "replace_color", "apply_filter"]],
  ["Selection and clipboard", ["select", "selection_edit", "clipboard"]],
  ["Palette", ["get_palette", "set_palette", "palette_edit", "save_palette"]],
  ["Tags, slices and properties", ["add_tag", "update_tag", "delete_tag", "add_slice", "update_slice", "delete_slice", "properties"]],
  ["Tilesets and tilemaps", ["tileset", "tilemap"]],
  ["Rendering and export", ["render_preview", "export", "export_sprite_sheet", "import_sprite_sheet"]],
  ["Live session", ["recent_events", "ask_user"]],
];

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

function typeOf(s) {
  if (!s) return "any";
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(" \\| ");
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(typeOf).join(" \\| ");
  if (s.type === "array") {
    if (Array.isArray(s.items)) return `[${s.items.map(typeOf).join(", ")}]`;
    return `${typeOf(s.items)}[]`;
  }
  if (s.type === "object") return s.properties ? "object" : "object (any keys)";
  if (Array.isArray(s.type)) return s.type.join(" \\| ");
  if (s.type === "integer") return "integer";
  return s.type ?? "any";
}

function range(s) {
  const parts = [];
  if (s.minimum !== undefined) parts.push(`min ${s.minimum}`);
  if (s.exclusiveMinimum !== undefined) parts.push(`> ${s.exclusiveMinimum}`);
  if (s.maximum !== undefined) parts.push(`max ${s.maximum}`);
  if (s.minItems !== undefined) parts.push(`at least ${s.minItems} item(s)`);
  return parts.length ? ` (${parts.join(", ")})` : "";
}

// Flattens nested object parameters into dotted rows (brush.size, grid.show...).
function rows(props, required, prefix = "") {
  const out = [];
  for (const [name, s] of Object.entries(props ?? {})) {
    const full = prefix + name;
    out.push(`| \`${full}\` | ${typeOf(s)} | ${required.includes(name) ? "yes" : ""} | ${esc(s.description)}${range(s)} |`);
    const obj = s.type === "object" ? s : (s.anyOf ?? []).find((x) => x.type === "object" && x.properties);
    if (obj?.properties) out.push(...rows(obj.properties, obj.required ?? [], `${full}.`));
    if (s.type === "array" && s.items?.type === "object" && s.items.properties) {
      out.push(...rows(s.items.properties, s.items.required ?? [], `${full}[].`));
    }
  }
  return out;
}

const byName = new Map(tools.map((t) => [t.name, t]));
const placed = new Set(SECTIONS.flatMap(([, names]) => names));
const other = tools.filter((t) => !placed.has(t.name)).map((t) => t.name);
const sections = other.length ? [...SECTIONS, ["Other", other]] : SECTIONS;

let md = `# Tool reference\n\n`;
md += `Generated by \`npm run docs\` from the schemas the server registers (${tools.length} tools). Do not edit by hand.\n\n`;
md += `Most tools also take \`backend\` (\`"auto"\`, \`"live"\` or \`"batch"\`) and, when they change a sprite, \`save\`. Both are described once in [Common parameters](#common-parameters) and left out of the tables below.\n\n`;
md += `## Contents\n\n`;
for (const [title, names] of sections) {
  md += `- ${title}: ${names.filter((n) => byName.has(n)).map((n) => `[${n}](#${n.replace(/_/g, "_")})`).join(", ")}\n`;
}
md += `\n## Common parameters\n\n| Parameter | Type | Meaning |\n| --- | --- | --- |\n`;
md += `| \`backend\` | \`"auto"\` \\| \`"live"\` \\| \`"batch"\` | \`auto\` (default) uses a connected Aseprite window, otherwise a headless \`aseprite -b\` process. |\n`;
md += `| \`save\` | boolean | Batch mode only: write changes back to the sprite file (default true). |\n\n`;
md += `## Server instructions\n\nThe server sends these instructions to the client when it connects:\n\n\`\`\`text\n${instructions.trim()}\n\`\`\`\n`;

for (const [title, names] of sections) {
  md += `\n## ${title}\n`;
  for (const name of names) {
    const t = byName.get(name);
    if (!t) continue;
    const props = { ...(t.inputSchema.properties ?? {}) };
    delete props.backend;
    delete props.save;
    md += `\n### ${name}\n\n${t.description}\n\n`;
    const flags = [];
    if (t.annotations?.readOnlyHint) flags.push("read-only");
    if (t.annotations?.destructiveHint) flags.push("destructive");
    if (flags.length) md += `Hints: ${flags.join(", ")}.\n\n`;
    const r = rows(props, t.inputSchema.required ?? []);
    if (r.length) md += `| Parameter | Type | Required | Description |\n| --- | --- | --- | --- |\n${r.join("\n")}\n`;
    else md += `No parameters.\n`;
  }
}

mkdirSync(path.join(root, "docs"), { recursive: true });
writeFileSync(path.join(root, "docs", "tools.md"), md);
console.log(`docs/tools.md: ${tools.length} tools`);
